function getElement(id) {
  const node = document.getElementById(id);
  if (!node) {
    console.warn(`[ui] 未找到 DOM 元素：#${id}`);
  }
  return node;
}

function buildElementGroup(ids) {
  return Object.fromEntries(ids.map(id => [id, getElement(id)]));
}

const uiGrouped = Object.fromEntries(
  Object.entries(elementGroups).map(([name, ids]) => [name, buildElementGroup(ids)])
);

const ui = Object.assign({}, ...Object.values(uiGrouped));
